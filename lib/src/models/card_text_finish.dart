/// Tactile physical typography finishes applied to card numbers,
/// cardholder name, and expiration dates.
enum CardTextFinish {
  /// Flat, crisp anti-aliased digital print with subtle soft drop shadow.
  flat,

  /// Physical 3D letterpress embossed relief with dual-vector chiseled
  /// light highlights and deep cast shadows simulating plastic stamping.
  embossed,

  /// Directional metallic hot-stamped gold foil with specular glint.
  goldFoil,

  /// Directional liquid chrome silver platinum foil stamping.
  silverFoil,
}
